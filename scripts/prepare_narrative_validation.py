def _contract(
    chapter: int,
    title: str,
    phase: ArcPhase,
    functions: tuple[str, ...],
    question: str,
    action: str,
    alternatives: tuple[str, ...],
    cost: str,
    consequence: str,
    before: str,
    after: str,
    reveal: tuple[str, ...],
    withhold: tuple[str, ...],
    start: str,
    turn: str,
    end: str,
    foreshadow: tuple[str, ...],
    ending: str,
    target: int,
    forbidden: tuple[str, ...],
    *,
    arc_id: str = ARC_ID,
    arc_goal: str = "逐步确认信号、家庭秘密和文明计划的关系",
) -> NarrativeDecision:
    return NarrativeDecision(
        chapter=chapter,
        profile_id=PROFILE_ID,
        volume_id=VOLUME_ID,
        arc_id=arc_id,
        arc_phase=phase,
        arc_goal=arc_goal,
        inherited_pressure="林子轩已经发现信号并被带入龙渊，无法回到完全不知情的普通生活。",
        future_pressures=("神经干预代价将被具体揭示", "全球公布会把私人发现变成公共危机"),
        chapter_contract=ChapterContract(
            functions=functions,
            dramatic_question=question,
            protagonist_choice=ProtagonistChoice("林子轩", action, alternatives, cost, consequence),
            reader_change=ReaderChange(before, after),
            information=InformationPlan(reveal, withhold, (f"暂不一次解释{title}背后的全部真相",)),
            pressure_curve=PressureCurve(start, turn, end),
            foreshadow_actions=foreshadow,
            ending_shift=ending,
            target_chinese_chars=target,
            forbidden=forbidden,
        ),
    )


