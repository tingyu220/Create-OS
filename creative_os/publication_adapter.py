"""平台适配器的最小协议。"""
from __future__ import annotations
from typing import Any, Protocol, runtime_checkable
from .publication_models import ChapterSnapshot

@runtime_checkable
class PlatformAdapter(Protocol):
    def connect(self, *args: Any, **kwargs: Any) -> dict[str, Any]: ...
    def verify_target(self, target: Any, snapshot: ChapterSnapshot | None = None) -> dict[str, Any]: ...
    def prepare_chapter(self, snapshot: ChapterSnapshot, target: Any = None) -> dict[str, Any]: ...
    def fill_chapter(self, snapshot: ChapterSnapshot, target: Any = None, operation_id: str | None = None) -> dict[str, Any]: ...
    def publish(self, operation_id: str) -> dict[str, Any]: ...
    def query_result(self, operation_id: str) -> dict[str, Any]: ...
    def capture_evidence(self, operation_id: str) -> dict[str, Any]: ...

__all__ = ["PlatformAdapter"]
